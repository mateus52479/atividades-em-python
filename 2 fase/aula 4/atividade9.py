from math import ceil, floor

arrendondar = float(input("digite um numero decimal qualquer: "))

print(f"o valor arredondado para cima de {arrendondar} é {ceil(arrendondar)}")
print(f"o valor arredondado para baixo de {arrendondar} é {floor(arrendondar)}")